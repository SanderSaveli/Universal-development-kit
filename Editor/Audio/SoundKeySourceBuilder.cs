using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace SanderSaveli.UDK.Audio.Editor
{
    internal static class SoundKeySourceBuilder
    {
        private const string ROOT_NAME = "Sounds";
        private static readonly HashSet<string> KEYWORDS = new HashSet<string>(
            ("abstract as base bool break byte case catch char checked class const continue decimal default "
            + "delegate do double else enum event explicit extern false finally fixed float for foreach goto "
            + "if implicit in int interface internal is lock long namespace new null object operator out "
            + "override params private protected public readonly ref return sbyte sealed short sizeof "
            + "stackalloc static string struct switch this throw true try typeof uint ulong unchecked "
            + "unsafe ushort using virtual void volatile while __arglist __makeref __reftype __refvalue").Split(' '),
            StringComparer.Ordinal);

        internal static bool TryBuild(IReadOnlyList<string> ids, out string source, out string error)
        {
            Node root = new Node(ROOT_NAME);
            for (int i = 0; i < ids.Count; i++)
            {
                if (!TryAdd(root, ids[i], out error))
                {
                    source = null;
                    return false;
                }
            }

            StringBuilder builder = new StringBuilder();
            builder.Append("// <auto-generated />\nnamespace SanderSaveli.UDK.Audio\n{\n");
            WriteClass(builder, root, 1);
            builder.Append("}\n");
            source = builder.ToString();
            error = null;
            return true;
        }

        private static bool TryAdd(Node root, string id, out string error)
        {
            if (string.IsNullOrWhiteSpace(id))
            {
                error = "Sound ID is empty.";
                return false;
            }

            string[] segments = id.Split('/');
            Node parent = root;
            for (int i = 0; i < segments.Length; i++)
            {
                string segment = segments[i];
                if (!IsIdentifier(segment) || KEYWORDS.Contains(segment))
                {
                    error = "Sound ID '" + id + "' contains an invalid C# name: '" + segment + "'.";
                    return false;
                }

                if (string.Equals(segment, parent.Name, StringComparison.Ordinal))
                {
                    error = "Sound ID '" + id + "' repeats its enclosing class name '" + parent.Name + "'.";
                    return false;
                }

                if (parent.Id != null)
                {
                    error = "Sound IDs '" + parent.Id + "' and '" + id + "' conflict: a sound cannot also be a group.";
                    return false;
                }

                if (parent.Children.TryGetValue(segment, out Node child))
                {
                    if (!string.Equals(child.Name, segment, StringComparison.Ordinal))
                    {
                        error = "Sound ID '" + id + "' has a case conflict: '" + child.Name + "' / '" + segment + "'.";
                        return false;
                    }
                }
                else
                {
                    child = new Node(segment);
                    parent.Children.Add(segment, child);
                }

                parent = child;
            }

            if (parent.Id != null || parent.Children.Count > 0)
            {
                error = "Sound ID '" + id + "' is duplicated or already used as a group.";
                return false;
            }

            parent.Id = id;
            error = null;
            return true;
        }

        private static bool IsIdentifier(string value)
        {
            if (value.Length == 0)
                return false;

            for (int i = 0; i < value.Length; i++)
            {
                char character = value[i];
                UnicodeCategory category = char.GetUnicodeCategory(character);
                bool isLetter = char.IsLetter(character) || category == UnicodeCategory.LetterNumber;
                bool isContinuation = char.IsDigit(character) || category == UnicodeCategory.ConnectorPunctuation
                    || category == UnicodeCategory.NonSpacingMark || category == UnicodeCategory.SpacingCombiningMark;
                if (character != '_' && !isLetter && (i == 0 || !isContinuation))
                    return false;
            }

            return true;
        }

        private static void WriteClass(StringBuilder builder, Node node, int depth)
        {
            string indent = new string(' ', depth * 4);
            builder.Append(indent).Append("public static class ").Append(node.Name).Append("\n");
            builder.Append(indent).Append("{\n");
            foreach (KeyValuePair<string, Node> entry in node.Children)
            {
                Node child = entry.Value;
                if (child.Id == null)
                    WriteClass(builder, child, depth + 1);
                else
                    builder.Append(indent).Append("    public static readonly global::SanderSaveli.UDK.Audio.SoundId ")
                        .Append(child.Name).Append(" = new global::SanderSaveli.UDK.Audio.SoundId(\"")
                        .Append(child.Id).Append("\");\n");
            }

            builder.Append(indent).Append("}\n");
        }

        private sealed class Node
        {
            internal readonly string Name;
            internal readonly SortedDictionary<string, Node> Children =
                new SortedDictionary<string, Node>(StringComparer.OrdinalIgnoreCase);
            internal string Id;

            internal Node(string name)
            {
                Name = name;
            }
        }
    }
}
